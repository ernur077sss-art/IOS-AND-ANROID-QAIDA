/** Never overwrite edited/UGC content with a stale translation for a reused ID. */
export function localizeListing(listing: Listing, locale: Locale): Listing {
  if (locale !== "kk") return listing;
  const source = catalogue.find((item) => item.id === listing.id);
  if (!source) return listing;
  const key = listing.id.slice(-3);
  return {
    ...listing,
    title:
      source.title === listing.title
        ? translate(listing.title, locale)
        : listing.title,
    summary:
      source.summary === listing.summary
        ? (summaries[key] ?? listing.summary)
        : listing.summary,
    address:
      source.address === listing.address
        ? (addresses[key] ?? listing.address)
        : listing.address,
  };
}
